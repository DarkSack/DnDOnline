export type Locale = "es" | "en";
export const DICTIONARIES: Record<Locale, Record<I18nKey, string>> = { es, en };

export type I18n = {
  locale: Locale;
  setLocale: (l: Locale) => void;
  t: (key: I18nKey) => string;
  /** Traduce un código de error de la API. */
  tError: (code: string) => string;
};

export const I18nContext = createContext<I18n | null>(null);

/** Valor guardado (raza, clase, criatura del catálogo): traducido si es de la lista, tal cual si es texto libre o antiguo. */
export function labelOf(t: I18n["t"], prefix: "race" | "class" | "creature", value: string): string {
  const key = `${prefix}.${value}`;
  return key in es ? t(key as I18nKey) : value;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used within I18nProvider");
  return ctx;
}
